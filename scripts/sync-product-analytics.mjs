import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS_TARGET = resolve(root, 'docs/lit-analytics.js');

// Mintlify includes every .js file in docs/ as a classic <script>, so the docs
// copy is the shared module wrapped in an IIFE with a page/CTA bootstrap.
export function buildDocsScript() {
  const client = readFileSync(resolve(root, 'lit-static/analytics.js'), 'utf8')
    .replace(/^export function /m, 'function ');
  return `// GENERATED by scripts/sync-product-analytics.mjs from lit-static/analytics.js.
// Do not edit; Mintlify loads every .js file in docs/ on every page.
(() => {
${client}
const analytics = createAnalytics("docs");
const destinations = {
  "dashboard.chipotle.litprotocol.com": "dashboard",
  "keychain.litprotocol.com": "keychain",
  "litprotocol.com": "marketing",
  "www.litprotocol.com": "marketing",
};
const page = () => analytics.page(location.pathname);
page();
// Mintlify swaps pages client-side; this event does not fire on first load.
window.addEventListener("mintlify:navigate", page);
document.addEventListener("click", (event) => {
  const link = event.target instanceof Element ? event.target.closest("a[href]") : null;
  if (!(link instanceof HTMLAnchorElement)) return;
  const destination = destinations[link.hostname];
  if (destination) analytics.capture("product_cta_clicked", { destination });
});
})();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const targets = [resolve(root, 'lit-agent-keychain/web/src')];
  // Pass the marketing checkout explicitly; it is a separate repository.
  if (process.argv[2]) targets.push(resolve(process.argv[2], 'src/lib'));
  for (const target of targets) {
    mkdirSync(target, { recursive: true });
    for (const name of ['analytics.js', 'analytics.d.ts']) {
      copyFileSync(resolve(root, 'lit-static', name), resolve(target, name));
    }
  }
  writeFileSync(DOCS_TARGET, buildDocsScript());
}
